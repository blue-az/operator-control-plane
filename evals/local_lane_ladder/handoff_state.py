#!/usr/bin/env python3
"""Regenerate a CURRENT STATE block at the top of an append-only handoff.

WHY THIS EXISTS
---------------
Append-only is right for the record and wrong for the reader. HANDOFF_2026-09-06.md
grew to seven correction and finding sections while line 77 near the top still
stated a comparison superseded four increments earlier. Every reader starting at
the top met the wrong instruction first, and at least two acted on it.

Patching line 77 would destroy the audit trail. So instead: sections carry a
supersession marker, and this script renders an index from them. Nothing is
rewritten. The reader gets current state first and the history stays intact below.

MARKER FORMAT -- place directly under a section heading:

    <!-- SUPERSEDED-BY: Correction #4 | SCOPE: full | note text -->

SCOPE is `full` (do not cite this section) or `partial` (parts stand, see note).
Sections with no marker are reported as current. This script does not judge, it
reads markers -- deciding what is superseded is a human call and stays one.

USAGE
    ./handoff_state.py HANDOFF_2026-09-06.md          # rewrite in place
    ./handoff_state.py HANDOFF_2026-09-06.md --check  # exit 1 if stale
"""
import re, sys
from pathlib import Path

START, END = "<!-- STATE:START -->", "<!-- STATE:END -->"
MARKER = re.compile(r"<!--\s*SUPERSEDED-BY:\s*(?P<by>[^|]+?)\s*\|\s*SCOPE:\s*(?P<scope>full|partial)\s*(?:\|\s*(?P<note>.*?))?\s*-->")

def build(text):
    body = text.split(END, 1)[1] if END in text else text
    body = body.lstrip("\n")   # normalise: the join below owns the blank line
    lines, sections = body.splitlines(), []
    for i, ln in enumerate(lines):
        if not ln.startswith("## "):
            continue
        title = ln[3:].strip()
        m = None
        for look in lines[i + 1:i + 4]:
            m = MARKER.search(look)
            if m: break
        sections.append((title, m))

    rows, live = [], 0
    for title, m in sections:
        if m is None:
            rows.append(f"| {title} | **current** | |")
            live += 1
        else:
            scope = m.group("scope")
            tag = "**SUPERSEDED**" if scope == "full" else "*partial*"
            note = (m.group("note") or "").strip()
            rows.append(f"| {title} | {tag} by {m.group('by').strip()} | {note} |")

    out = [START,
           "<!-- Generated by handoff_state.py. Do not hand-edit. Edit the markers instead. -->",
           "",
           "## CURRENT STATE",
           "",
           f"{len(sections)} sections, {live} current. **Read this table before citing "
           "anything below it.** A section marked SUPERSEDED must not be quoted. A "
           "section marked partial has parts that stand -- the note says which.",
           "",
           "| section | status | note |", "|---|---|---|", *rows, "", END]
    return "\n".join(out) + "\n\n" + body

def main():
    path = Path(sys.argv[1])
    text = path.read_text(encoding="utf-8")
    new = build(text)
    if "--check" in sys.argv:
        if new != text:
            print(f"STALE: {path} -- run handoff_state.py to regenerate"); sys.exit(1)
        print(f"OK: {path} state block is current"); return
    path.write_text(new, encoding="utf-8")
    print(f"regenerated CURRENT STATE in {path}")

main()
